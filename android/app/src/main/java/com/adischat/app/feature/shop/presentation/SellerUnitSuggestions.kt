internal fun suggestedSellingUnitCodes(categoryId: String): Set<String> =
    categoryUnitSuggestions[categoryId].orEmpty()

internal fun orderSellingUnits(
    units: List<ShopSellingUnitDto>,
    categoryId: String,
    selectedCode: String,
): List<ShopSellingUnitDto> {
    val suggested = suggestedSellingUnitCodes(categoryId)
    return units.sortedWith(
        compareBy<ShopSellingUnitDto> {
            when {
                it.code.equals(selectedCode, ignoreCase = true) -> 0
                it.code in suggested -> 1
                else -> 2
            }
        }.thenBy { it.displayOrder },
    )
}
